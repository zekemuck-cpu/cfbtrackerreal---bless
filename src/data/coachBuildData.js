// Coach Builder — archetypes, packages, and budget formula.

export function computeBudget(level, preorder = false, mvp = false) {
  const base = level >= 1 ? (level - 1) * 25 + 10 : 0
  return base + (preorder ? 100 : 0) + (mvp ? 150 : 0)
}

